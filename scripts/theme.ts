/**
 * Writes app/m3-tokens.css: Material 3 colour roles for light and dark, from
 * one seed colour, as CSS variables. Run `bun run theme` after changing SEED.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { argbFromHex, hexFromArgb, Hct, MaterialDynamicColors, SchemeTonalSpot, type DynamicColor } from "@material/material-color-utilities";

const SEED = "#0b6e99";

const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
  "surfaceDim", "surfaceBright",
  "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "inverseSurface", "inverseOnSurface", "inversePrimary",
  "outline", "outlineVariant", "scrim", "shadow",
] as const;

const kebab = (name: string) => name.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);

function block(isDark: boolean) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
  const colors = MaterialDynamicColors as unknown as Record<string, DynamicColor>;
  return ROLES.map((role) => `  --md-sys-color-${kebab(role)}: ${hexFromArgb(colors[role].getArgb(scheme))};`).join("\n");
}

const css = `/* Generated by scripts/theme.ts from seed ${SEED}. Do not edit. */
:root {
${block(false)}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(true).replace(/^/gm, "  ")}
  }
}
`;

writeFileSync(path.resolve(import.meta.dirname, "../app/m3-tokens.css"), css);
console.log("Wrote app/m3-tokens.css");

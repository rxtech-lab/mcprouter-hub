/* eslint-disable @typescript-eslint/no-require-imports -- Postman handlers run as CommonJS. */
const http = require("node:http");
/* eslint-enable @typescript-eslint/no-require-imports */
// Synthetic structural examples based on the Chrome playground, not live captures.
const stories = [0, 1, 2].map((i) => ({ type: "article", internalID: `TNF3BYKIP3IM0${i}`,
  title: `Trade Bloom example ${i}`, longURL: `https://www.bloomberg.com/news/articles/2026-10-24/example-${i}`,
  published: 1792857610 - i, summary: "", autoGeneratedSummary: "Example summary" }));
http.createServer((req, res) => {
  res.setHeader("Content-Type", "application/json");
  if (req.headers["x-rapidapi-host"] !== "trade-bloom-finance.p.rapidapi.com" || !req.headers["x-rapidapi-key"]) {
    res.writeHead(401).end(JSON.stringify({ message: "Missing auth" })); return;
  }
  const mode = req.headers["x-rapidapi-key"];
  if (mode === "simulation-http" || mode === "simulation-both-error") { res.writeHead(429).end("Rate limit: secret-echo-must-not-leak"); return; }
  if (mode === "simulation-json") { res.end("<html>Maintenance</html>"); return; }
  if (mode === "simulation-business-error") { res.end(JSON.stringify({ status_code: 401, status: false })); return; }
  if (mode === "simulation-malformed") { res.end(JSON.stringify({ status_code: 200, status: true, data: {} })); return; }
  const url = new URL(req.url, "http://localhost");
  if (req.method === "GET" && url.pathname === "/news/top-news") {
    res.end(JSON.stringify({ status_code: 200, status: true, data: { modules: [
      { stories: mode === "simulation-empty" ? [] : [stories[0], stories[0], { type: "video" }, ...stories.slice(1)] },
    ] } })); return;
  }
  if (req.method === "GET" && url.pathname === "/stories/detail") {
    // Only the provider's failure envelope has been observed live for detail.
    res.end(JSON.stringify({ status_code: 401, status: false })); return;
  }
  res.writeHead(501).end(JSON.stringify({ error: "Endpoint not modeled" }));
}).listen(process.env.PORT);

import { parse as parseYaml } from "yaml";
import { serviceSpec, type ParamSpec, type ServiceSpec } from "./schema";

/**
 * Pure part of the code generator: YAML text in, file contents out. The CLI in
 * `scripts/codegen.ts` does the file system work around it.
 */

export type ServiceSource = {
  /** Directory name under `mcp/services/`; must equal the YAML `id`. */
  directory: string;
  yaml: string;
  /** Exported names found in `handlers.ts`, or null when the file is absent. */
  handlerExports: Set<string> | null;
};

export class CodegenError extends Error {
  constructor(readonly problems: string[]) {
    super(`Service definitions are invalid:\n${problems.map((problem) => `  - ${problem}`).join("\n")}`);
    this.name = "CodegenError";
  }
}

const HEADER = "// Generated by scripts/codegen.ts. Do not edit; change the service YAML and run `bun run codegen`.";

export function parseService(source: ServiceSource): { spec: ServiceSpec | null; problems: string[] } {
  const where = `mcp/services/${source.directory}/service.yaml`;
  let raw: unknown;
  try {
    raw = parseYaml(source.yaml);
  } catch (error) {
    return { spec: null, problems: [`${where}: invalid YAML: ${(error as Error).message}`] };
  }
  const parsed = serviceSpec.safeParse(raw);
  if (!parsed.success) {
    return {
      spec: null,
      problems: parsed.error.issues.map((issue) => `${where}: ${issue.path.join(".") || "(root)"}: ${issue.message}`),
    };
  }
  const spec = parsed.data;
  const problems: string[] = [];
  if (spec.id !== source.directory) problems.push(`${where}: id "${spec.id}" must match its directory name`);
  for (const tool of spec.tools) {
    if (!tool.handler) continue;
    if (!source.handlerExports) {
      problems.push(`${where}: tool ${tool.name} uses handler "${tool.handler}" but handlers.ts does not exist`);
    } else if (!source.handlerExports.has(tool.handler)) {
      problems.push(`${where}: tool ${tool.name} uses handler "${tool.handler}" but handlers.ts does not export it`);
    }
  }
  return { spec: problems.length ? null : spec, problems };
}

/** Exported identifiers in a handlers.ts source, found without importing it. */
export function findExports(source: string) {
  const names = new Set<string>();
  for (const match of source.matchAll(/export\s+(?:async\s+)?(?:function|const|let)\s+([A-Za-z_$][\w$]*)/g)) names.add(match[1]);
  return names;
}

export function zodFor(param: ParamSpec): string {
  let expression: string;
  if (param.type === "string") {
    expression = param.enum ? `z.enum(${JSON.stringify(param.enum)})` : "z.string()";
    if (param.pattern) expression += `.regex(new RegExp(${JSON.stringify(param.pattern)}))`;
  } else if (param.type === "boolean") {
    expression = "z.boolean()";
  } else {
    if (param.enum) {
      const literals = param.enum.map((value) => `z.literal(${JSON.stringify(value)})`);
      expression = literals.length === 1 ? literals[0] : `z.union([${literals.join(", ")}])`;
    } else {
      expression = param.type === "integer" ? "z.number().int()" : "z.number()";
      if (param.minimum !== undefined) expression += `.min(${param.minimum})`;
      if (param.maximum !== undefined) expression += `.max(${param.maximum})`;
    }
  }
  if (param.description) expression += `.describe(${JSON.stringify(param.description)})`;
  if (param.default !== undefined) expression += `.default(${JSON.stringify(param.default)})`;
  else if (!param.required) expression += ".optional()";
  return expression;
}

function indent(text: string, spaces: number) {
  const pad = " ".repeat(spaces);
  return text
    .split("\n")
    .map((line, index) => (index === 0 ? line : pad + line))
    .join("\n");
}

export function variableName(id: string) {
  return id.replace(/-([a-z0-9])/g, (_, char: string) => char.toUpperCase());
}

export function generateServiceModule(spec: ServiceSpec): string {
  const usesHandlers = spec.tools.some((tool) => tool.handler);
  const { tools, ...serviceFields } = spec;
  const toolBlocks = tools.map((tool) => {
    const { handler, ...toolSpec } = tool;
    const inputLines = Object.entries(tool.input).map(([name, param]) => `    ${JSON.stringify(name)}: ${zodFor(param)},`);
    const lines = [
      "{",
      `  name: ${JSON.stringify(tool.name)},`,
      ...(tool.title ? [`  title: ${JSON.stringify(tool.title)},`] : []),
      `  description: ${JSON.stringify(tool.description)},`,
      `  spec: ${indent(JSON.stringify(toolSpec, null, 2), 2)},`,
      inputLines.length ? `  inputSchema: z.object({\n${inputLines.join("\n")}\n  }),` : "  inputSchema: z.object({}),",
      ...(handler ? [`  handler: handlers.${handler},`] : []),
      "}",
    ];
    return indent(lines.join("\n"), 4);
  });
  const serviceJson = JSON.stringify(serviceFields, null, 2).replace(/\n}$/, "");

  return [
    HEADER,
    `// Source: mcp/services/${spec.id}/service.yaml`,
    'import type { McpServer } from "@modelcontextprotocol/server";',
    'import { z } from "zod";',
    'import { registerServices } from "@/lib/mcp/register";',
    'import type { CallerContext, ServiceDefinition } from "@/lib/mcp/types";',
    ...(usesHandlers ? [`import * as handlers from "@/mcp/services/${spec.id}/handlers";`] : []),
    "",
    `export const service: ServiceDefinition = ${serviceJson},`,
    "  tools: [",
    ...toolBlocks.map((block) => `    ${block},`),
    "  ],",
    "};",
    "",
    "export function registerTools(server: McpServer, caller: CallerContext) {",
    "  registerServices(server, [service], caller);",
    "}",
    "",
  ].join("\n");
}

export function generateRegistry(specs: ServiceSpec[]): string {
  return [
    HEADER,
    'import type { ServiceDefinition } from "@/lib/mcp/types";',
    ...specs.map((spec) => `import { service as ${variableName(spec.id)} } from "./services/${spec.id}";`),
    "",
    `export const services: readonly ServiceDefinition[] = [${specs.map((spec) => variableName(spec.id)).join(", ")}];`,
    "",
    "export const serviceById = new Map(services.map((service) => [service.id, service]));",
    "",
  ].join("\n");
}

export type Manifest = {
  services: Array<{
    id: string;
    title: string;
    description?: string;
    datasets: string[];
    tools: Array<{ name: string; description: string }>;
  }>;
  /** Dataset id → service ids that convert it. */
  datasets: Record<string, string[]>;
};

export function buildManifest(specs: ServiceSpec[]): Manifest {
  const datasets: Record<string, string[]> = {};
  for (const spec of specs) {
    for (const id of spec.datasets) (datasets[id] ??= []).push(spec.id);
  }
  return {
    services: specs.map((spec) => ({
      id: spec.id,
      title: spec.title,
      ...(spec.description ? { description: spec.description } : {}),
      datasets: spec.datasets,
      tools: spec.tools.map((tool) => ({ name: tool.name, description: tool.description })),
    })),
    datasets: Object.fromEntries(Object.entries(datasets).sort(([a], [b]) => a.localeCompare(b))),
  };
}

/** Validate every source and return the generated files, keyed by path relative to the repo root. */
export function generate(sources: ServiceSource[]): Map<string, string> {
  const problems: string[] = [];
  const specs: ServiceSpec[] = [];
  for (const source of [...sources].sort((a, b) => a.directory.localeCompare(b.directory))) {
    const result = parseService(source);
    problems.push(...result.problems);
    if (result.spec) specs.push(result.spec);
  }
  const owners = new Map<string, string>();
  for (const spec of specs) {
    for (const tool of spec.tools) {
      const owner = owners.get(tool.name);
      if (owner) problems.push(`tool name ${tool.name} is used by both ${owner} and ${spec.id}`);
      owners.set(tool.name, spec.id);
    }
  }
  if (problems.length) throw new CodegenError(problems);

  const files = new Map<string, string>();
  for (const spec of specs) files.set(`generated/services/${spec.id}.ts`, generateServiceModule(spec));
  files.set("generated/registry.ts", generateRegistry(specs));
  files.set("generated/manifest.json", `${JSON.stringify(buildManifest(specs), null, 2)}\n`);
  return files;
}

import type { HandlerContext, ToolHandler } from "@/lib/mcp/types";
import { UpstreamError } from "@/lib/mcp/fetcher";

type RapidProvider = "trade-bloom" | "reuters";
type Provider = RapidProvider | "hacker-news";
type Row = Record<string, unknown>;
type News = { id: string; provider: Provider; title: string; url: string; publishedAt: string | null; summary: string | null };
const providers: Provider[] = ["trade-bloom", "reuters", "hacker-news"];
const hosts = { "trade-bloom": "trade-bloom-finance.p.rapidapi.com", reuters: "reuters-api.p.rapidapi.com" };

function record(value: unknown): value is Row {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function malformed(provider: Provider): never {
  throw new UpstreamError("upstream_parse", `${provider} returned an invalid news response`);
}

class ProviderConfigurationError extends Error {}

function apiKey() {
  const key = process.env.RAPIDAPI_KEY?.trim();
  if (!key) throw new ProviderConfigurationError("Configure RAPIDAPI_KEY in the server .env and subscribe to both news APIs on RapidAPI");
  return key;
}

function articleUrl(value: unknown, provider: RapidProvider): string {
  if (typeof value !== "string" || value.length > 2900) return malformed(provider);
  let url: URL;
  try { url = new URL(value); } catch { return malformed(provider); }
  const domain = provider === "reuters" ? "reuters.com" : "bloomberg.com";
  if (url.protocol !== "https:" || ![domain, `www.${domain}`].includes(url.hostname) ||
      url.username || url.password || url.port || url.hash || url.pathname === "/") return malformed(provider);
  return url.href;
}

function publishedAt(value: unknown): string | null {
  const timestamp = typeof value === "number" ? value * 1000 : typeof value === "string" ? Date.parse(value) : NaN;
  return Number.isFinite(timestamp) && Math.abs(timestamp) <= 8.64e15 ? new Date(timestamp).toISOString() : null;
}

/** Never return upstream error bodies: they may echo request credentials. */
async function request(provider: RapidProvider, path: string, query: Record<string, string>, key: string, context: HandlerContext) {
  const override = process.env[provider === "trade-bloom" ? "TRADE_BLOOM_BASE_URL" : "REUTERS_BASE_URL"];
  const url = new URL(`${(override || `https://${hosts[provider]}`).replace(/\/$/, "")}${path}`);
  for (const [name, value] of Object.entries(query)) url.searchParams.set(name, value);
  let body: unknown;
  try {
    body = await context.fetchUpstream(url.href, {
      headers: { "x-rapidapi-key": key, "x-rapidapi-host": hosts[provider] },
      // The shared cache key does not include auth headers. Keep paid/private data out of it.
      cacheTtl: 0,
    });
  } catch (error) {
    if (error instanceof UpstreamError) {
      throw new UpstreamError(error.code,
        `${provider} request failed${error.status ? ` (HTTP ${error.status})` : ""}`, error.status);
    }
    throw new UpstreamError("upstream_network", `${provider} request failed`);
  }
  if (record(body) && (body.status === false || body.status === "error" || body.status === "failed" ||
      (typeof body.status_code === "number" && body.status_code >= 400))) {
    const status = typeof body.status_code === "number" ? body.status_code : undefined;
    throw new UpstreamError("upstream_http", `${provider} reported a provider error${status ? ` (${status})` : ""}`, status);
  }
  return body;
}

function normalize(row: unknown, provider: RapidProvider): News {
  if (!record(row) || typeof row.title !== "string" || !row.title.trim()) return malformed(provider);
  const url = articleUrl(provider === "reuters" ? row.link : row.longURL ?? row.shortURL, provider);
  if (provider === "trade-bloom" && (typeof row.internalID !== "string" || !/^[A-Za-z0-9]{14}$/.test(row.internalID))) return malformed(provider);
  const reference = provider === "reuters" ? Buffer.from(url).toString("base64url") : row.internalID;
  const summary = row.summary || row.autoGeneratedSummary;
  return { id: `${provider}:${reference}`, provider, title: row.title.slice(0, 1000), url,
    publishedAt: publishedAt(provider === "reuters" ? row.published_at : row.published),
    summary: typeof summary === "string" && summary ? summary.slice(0, 2000) : null };
}

async function headlines(provider: RapidProvider, x: number, key: string, context: HandlerContext) {
  const body = await request(provider, provider === "reuters" ? "/latest" : "/news/top-news",
    provider === "reuters" ? { limit: String(x) } : {}, key, context);
  let rows: unknown[];
  if (provider === "reuters") {
    if (!Array.isArray(body)) return malformed(provider);
    rows = body;
  } else {
    if (!record(body) || body.status !== true || body.status_code !== 200 || !record(body.data) || !Array.isArray(body.data.modules)) return malformed(provider);
    rows = body.data.modules.flatMap((module: unknown) => {
      if (!record(module) || !Array.isArray(module.stories)) return malformed(provider);
      // Home-page modules also contain videos, ads and newsletters; list detail-capable articles.
      return module.stories.filter((story: unknown) => record(story) && story.type === "article");
    });
  }
  const unique = new Map<string, News>();
  for (const row of rows) {
    const news = normalize(row, provider);
    if (!unique.has(news.id)) unique.set(news.id, news);
    if (unique.size === x) break;
  }
  return [...unique.values()];
}

async function hackerNewsRequest(path: string, context: HandlerContext) {
  const base = process.env.HACKER_NEWS_BASE_URL || "https://hacker-news.firebaseio.com/v0";
  try {
    // Public API: never forward RapidAPI credentials to this source.
    return await context.fetchUpstream(`${base.replace(/\/$/, "")}${path}`, { cacheTtl: 0 });
  } catch (error) {
    if (error instanceof UpstreamError) throw new UpstreamError(error.code, "hacker-news request failed", error.status);
    throw new UpstreamError("upstream_network", "hacker-news request failed");
  }
}

function storyId(value: unknown): value is number {
  return typeof value === "number" && Number.isSafeInteger(value) && value > 0;
}

function hackerNewsStory(body: unknown, id: number): Row | null {
  if (body === null) return null;
  if (!record(body) || body.id !== id) return malformed("hacker-news");
  if (body.deleted === true || body.dead === true || body.type !== "story") return null;
  if (typeof body.title !== "string" || !body.title.trim()) return malformed("hacker-news");
  return body;
}

function hackerNewsUrl(row: Row): string {
  const fallback = `https://news.ycombinator.com/item?id=${row.id}`;
  if (typeof row.url !== "string" || row.url.length > 2900) return fallback;
  try {
    const url = new URL(row.url);
    return ["http:", "https:"].includes(url.protocol) && !url.username && !url.password ? url.href : fallback;
  } catch { return fallback; }
}

async function hackerNewsHeadlines(x: number, context: HandlerContext): Promise<News[]> {
  const body = await hackerNewsRequest("/topstories.json", context);
  if (!Array.isArray(body) || !body.every(storyId)) return malformed("hacker-news");
  // Bound fan-out to x unique ranked candidates, at most ten item requests at once.
  const ids = [...new Set<number>(body)].slice(0, x);
  const news: News[] = [];
  for (let offset = 0; offset < ids.length; offset += 10) {
    const rows = await Promise.all(ids.slice(offset, offset + 10).map(async (id) =>
      hackerNewsStory(await hackerNewsRequest(`/item/${id}.json`, context), id)));
    for (const row of rows) {
      if (!row) continue;
      news.push({ id: `hacker-news:${row.id}`, provider: "hacker-news", title: (row.title as string).slice(0, 1000),
        url: hackerNewsUrl(row), publishedAt: publishedAt(row.time),
        summary: typeof row.text === "string" && row.text ? row.text.slice(0, 2000) : null });
    }
  }
  return news;
}

export const listTopNews: ToolHandler = async (input, context) => {
  const x = input.x === undefined ? 10 : Number(input.x);
  if (!Number.isInteger(x) || x < 1 || x > 50) throw new Error("x must be an integer from 1 to 50");
  const results = await Promise.allSettled(providers.map(async (provider) =>
    provider === "hacker-news" ? hackerNewsHeadlines(x, context) : headlines(provider, x, apiKey(), context)));
  const status = results.map((result, i) => result.status === "fulfilled"
    ? { provider: providers[i], status: "ok" as const, returned: result.value.length }
    : { provider: providers[i], status: "error" as const, returned: 0,
      code: result.reason instanceof ProviderConfigurationError ? "configuration_error"
        : result.reason instanceof UpstreamError ? result.reason.code : "upstream_parse",
      httpStatus: result.reason instanceof UpstreamError ? result.reason.status ?? null : null });
  if (results.every((result) => result.status === "rejected")) {
    throw new Error(`All news providers failed: ${status.map((s) => `${s.provider}: ${"code" in s ? s.code : s.status}${"httpStatus" in s && s.httpStatus ? ` (${s.httpStatus})` : ""}`).join("; ")}`);
  }
  const news: News[] = [];
  for (let i = 0; i < x; i++) {
    for (const result of results) {
      if (result.status === "fulfilled" && result.value[i]) news.push(result.value[i]);
    }
  }
  return { requestedPerProvider: x, returned: news.length, partial: status.some((s) => s.status === "error"), providers: status, news };
};

export const getNewsDetail: ToolHandler = async (input, context) => {
  const id = String(input.id ?? "");
  if (/^hacker-news:[1-9][0-9]{0,15}$/.test(id)) {
    const reference = Number(id.slice("hacker-news:".length));
    if (!storyId(reference)) throw new Error("Invalid Hacker News id");
    const article = hackerNewsStory(await hackerNewsRequest(`/item/${reference}.json`, context), reference);
    if (!article) throw new UpstreamError("upstream_http", "Hacker News story not found or unavailable", 404);
    if (Buffer.byteLength(JSON.stringify(article)) > 90_000) throw new UpstreamError("upstream_parse", "hacker-news article exceeds the 90 KB detail limit");
    return { id, provider: "hacker-news", article };
  }
  let provider: RapidProvider;
  let path: string;
  let query: Record<string, string>;
  if (/^trade-bloom:[A-Za-z0-9]{14}$/.test(id)) {
    provider = "trade-bloom"; path = "/stories/detail"; query = { id: id.slice("trade-bloom:".length) };
  } else if (/^reuters:[A-Za-z0-9_-]{1,4000}$/.test(id)) {
    provider = "reuters"; path = "/details";
    const reference = id.slice("reuters:".length);
    const decoded = Buffer.from(reference, "base64url").toString("utf8");
    if (Buffer.from(decoded).toString("base64url") !== reference) throw new Error("Invalid Reuters news id");
    query = { url: articleUrl(decoded, provider) };
  } else { throw new Error("Invalid news id; use the exact provider-prefixed id from list_top_news"); }
  const body = await request(provider, path, query, apiKey(), context);
  if (!record(body) || !record(body.data) || !Object.keys(body.data).length ||
      (provider === "reuters" ? body.status !== "success" : body.status !== true || body.status_code !== 200)) return malformed(provider);
  // Preserve the provider's content tree rather than invent a shared full-text schema.
  if (Buffer.byteLength(JSON.stringify(body.data)) > 90_000) throw new UpstreamError("upstream_parse", `${provider} article exceeds the 90 KB detail limit`);
  return { id, provider, article: body.data };
};
